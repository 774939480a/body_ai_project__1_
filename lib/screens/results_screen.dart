class _AnglesGrid extends StatelessWidget {
  const _AnglesGrid({required this.measurement});
  final MeasurementResult measurement;

  @override
  Widget build(BuildContext context) {
    final m = measurement;

    final pairs = <_AnglePair>[
      _AnglePair('L. Elbow',    m.elbowAngleLeft,    AppColors.neonPurple),
      _AnglePair('R. Elbow',    m.elbowAngleRight,   AppColors.neonPurple),
      _AnglePair('L. Knee',     m.kneeAngleLeft,     AppColors.neonGreen),
      _AnglePair('R. Knee',     m.kneeAngleRight,    AppColors.neonGreen),
      _AnglePair('L. Shoulder', m.shoulderAngleLeft, AppColors.neonCyan),
      _AnglePair('R. Shoulder', m.shoulderAngleRight,AppColors.neonCyan),
      _AnglePair('L. Hip',      m.hipAngleLeft,      AppColors.neonBlue),
      _AnglePair('R. Hip',      m.hipAngleRight,     AppColors.neonBlue),
    ].where((p) => p.value != null).toList();

    return Wrap(
      spacing: 10,
      runSpacing: 10,
      children: pairs.map((p) => _AngleTile(pair: p)).toList(),
    );
  }
}

class _AnglePair {
  const _AnglePair(this.label, this.value, this.color);
  final String  label;
  final double? value;
  final Color   color;
}

class _AngleTile extends StatelessWidget {
  const _AngleTile({required this.pair});
  final _AnglePair pair;

  @override
  Widget build(BuildContext context) {
    return Container(
      width: (MediaQuery.of(context).size.width - 60) / 2,
      padding: const EdgeInsets.symmetric(horizontal: 10, vertical: 8),
      decoration: BoxDecoration(
        color:        pair.color.withOpacity(0.07),
        borderRadius: BorderRadius.circular(8),
        border: Border.all(color: pair.color.withOpacity(0.3)),
      ),
      child: Row(
        mainAxisAlignment: MainAxisAlignment.spaceBetween,
        children: [
          Text(
            pair.label,
            style: const TextStyle(
              fontFamily: 'Courier',
              fontSize:   10,
              color:      AppColors.textSecondary,
            ),
          ),
          Text(
            '${pair.value!.toStringAsFixed(0)}°',
            style: TextStyle(
              fontFamily:  'Courier',
              fontSize:    14,
              fontWeight:  FontWeight.w700,
              color:       pair.color,
            ),
          ),
        ],
      ),
    );
  }
}

