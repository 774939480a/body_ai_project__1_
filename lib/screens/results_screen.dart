class _PostureSection extends StatelessWidget {
  const _PostureSection({required this.posture});
  final PostureResult posture;

  @override
  Widget build(BuildContext context) {
    Color statusColor;
    switch (posture.status) {
      case PostureStatus.stable:           statusColor = AppColors.neonGreen;  break;
      case PostureStatus.unstableRotation: statusColor = AppColors.neonRed;    break;
      default:                             statusColor = AppColors.neonOrange;
    }

    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        // Status pill
        Container(
          padding: const EdgeInsets.symmetric(horizontal: 12, vertical: 6),
          decoration: BoxDecoration(
            color:        statusColor.withOpacity(0.12),
            borderRadius: BorderRadius.circular(6),
            border: Border.all(color: statusColor.withOpacity(0.5)),
          ),
          child: Text(
            posture.status.label,
            style: TextStyle(
              fontFamily:   'Courier',
              fontSize:     13,
              fontWeight:   FontWeight.w700,
              color:        statusColor,
              letterSpacing: 1.2,
            ),
          ),
        ),
        const SizedBox(height: 14),

        // Metrics
        _PostureMetric('Shoulder Tilt',
            '${posture.shoulderTiltDeg.toStringAsFixed(1)}°',
            threshold: '< ${PostureThresholds.shoulder}°'),
        _PostureMetric('Spine Tilt',
            '${posture.spineTiltDeg.toStringAsFixed(1)}°',
            threshold: '< ${PostureThresholds.spine}°'),
        _PostureMetric('Hip Tilt',
            '${posture.hipTiltDeg.toStringAsFixed(1)}°'),
        if (posture.zSkewRatio != null)
          _PostureMetric('Z-Axis Skew',
              '${(posture.zSkewRatio! * 100).toStringAsFixed(0)} %',
              threshold: '< ${(PostureThresholds.zSkew * 100).toStringAsFixed(0)} %'),
        if (posture.symmetryRatio != null)
          _PostureMetric('Arm Symmetry',
              '${(posture.symmetryRatio!.abs() * 100).toStringAsFixed(1)} %'),

        const SizedBox(height: 8),
        Text(
          'Stable frames: ${posture.stableFrameCount}',
          style: AppTextStyles.bodySmall,
        ),
      ],
    );
  }
}

/// Temporary constants class to avoid re-importing PostureConfig here.
class PostureThresholds {
  static const double shoulder = 5.0;
  static const double spine    = 7.0;
  static const double zSkew    = 0.35;
}

class _PostureMetric extends StatelessWidget {
  const _PostureMetric(this.label, this.value, {this.threshold});
  final String  label;
  final String  value;
  final String? threshold;

  @override
  Widget build(BuildContext context) {
    return Padding(
      padding: const EdgeInsets.symmetric(vertical: 4),
      child: Row(
        mainAxisAlignment: MainAxisAlignment.spaceBetween,
        children: [
          Text(label,
              style: const TextStyle(
                  fontFamily: 'Courier',
                  fontSize: 12,
                  color: AppColors.textSecondary)),
          Row(
            children: [
              Text(value,
                  style: const TextStyle(
                    fontFamily:  'Courier',
                    fontSize:    13,
                    fontWeight:  FontWeight.w700,
                    color:       AppColors.textPrimary,
                  )),
              if (threshold != null) ...[
                const SizedBox(width: 6),
                Text('(ideal $threshold)',
                    style: const TextStyle(
                        fontFamily: 'Courier',
                        fontSize:   9,
                        color:      AppColors.textDisabled)),
              ],
            ],
          ),
        ],
      ),
    );
  }
}

