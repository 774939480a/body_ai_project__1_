class _CaptureInfoRow extends StatelessWidget {
  const _CaptureInfoRow({required this.capturedAt, required this.calibration});
  final DateTime       capturedAt;
  final CalibrationData calibration;

  @override
  Widget build(BuildContext context) {
    final ts = capturedAt;
    final dateStr = '${ts.year}-${_p(ts.month)}-${_p(ts.day)}  '
        '${_p(ts.hour)}:${_p(ts.minute)}';

    return Row(
      children: [
        const Icon(Icons.schedule_rounded,
            color: AppColors.textSecondary, size: 14),
        const SizedBox(width: 6),
        Text(dateStr,
            style: AppTextStyles.bodySmall.copyWith(fontSize: 11)),
        const Spacer(),
        Container(
          padding: const EdgeInsets.symmetric(horizontal: 8, vertical: 3),
          decoration: BoxDecoration(
            color: (calibration.isCalibrated
                    ? AppColors.neonGreen
                    : AppColors.neonOrange)
                .withOpacity(0.12),
            borderRadius: BorderRadius.circular(5),
            border: Border.all(
              color: (calibration.isCalibrated
                      ? AppColors.neonGreen
                      : AppColors.neonOrange)
                  .withOpacity(0.5),
            ),
          ),
          child: Text(
            calibration.isCalibrated
                ? '✓  ${calibration.summary}'
                : 'UNCALIBRATED',
            style: TextStyle(
              fontFamily:   'Courier',
              fontSize:     9,
              fontWeight:   FontWeight.w700,
              color: calibration.isCalibrated
                  ? AppColors.neonGreen
                  : AppColors.neonOrange,
              letterSpacing: 0.6,
            ),
          ),
        ),
      ],
    );
  }

  String _p(int n) => n.toString().padLeft(2, '0');
}

