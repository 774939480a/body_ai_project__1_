// lib/screens/results_screen.dart
// ─────────────────────────────────────────────────────────────────────────────
// ResultsScreen — displayed after the shutter button is pressed.
//
// Shows a frozen snapshot of:
//   • All body measurements in centimetres
//   • Joint angles in degrees
//   • Posture analysis summary
//   • Calibration reference info
//
// The user can share the results as text or go back to live camera.
// ─────────────────────────────────────────────────────────────────────────────

import 'package:flutter/material.dart';
import 'package:flutter/services.dart';

import '../calibration/calibration_data.dart';
import '../core/themes/app_theme.dart';
import '../models/measurement_result.dart';
import '../posture/posture_result.dart';

class ResultsScreen extends StatelessWidget {
  const ResultsScreen({
    super.key,
    required this.measurement,
    required this.posture,
    required this.calibration,
    required this.capturedAt,
  });

  final MeasurementResult measurement;
  final PostureResult      posture;
  final CalibrationData    calibration;
  final DateTime           capturedAt;

  // ── Build ─────────────────────────────────────────────────────────────────

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      backgroundColor: AppColors.backgroundPrimary,
      appBar: _buildAppBar(context),
      body: SingleChildScrollView(
        padding: const EdgeInsets.fromLTRB(16, 12, 16, 32),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            // ── Capture info ────────────────────────────────────────────
            _CaptureInfoRow(
              capturedAt:  capturedAt,
              calibration: calibration,
            ),
            const SizedBox(height: 18),

            // ── Body measurements ───────────────────────────────────────
            _SectionCard(
              title: 'BODY MEASUREMENTS',
              icon:  Icons.straighten_rounded,
              color: AppColors.neonCyan,
              child: _MeasurementsGrid(measurement: measurement),
            ),
            const SizedBox(height: 14),

            // ── Joint angles ────────────────────────────────────────────
            _SectionCard(
              title: 'JOINT ANGLES',
              icon:  Icons.rotate_right_rounded,
              color: AppColors.neonPurple,
              child: _AnglesGrid(measurement: measurement),
            ),
            const SizedBox(height: 14),

            // ── Posture analysis ────────────────────────────────────────
            _SectionCard(
              title: 'POSTURE ANALYSIS',
              icon:  Icons.accessibility_new_rounded,
              color: _postureColor(posture.status),
              child: _PostureSection(posture: posture),
            ),
            const SizedBox(height: 24),

            // ── Action buttons ──────────────────────────────────────────
            _ActionButtons(
              onCopy:   () => _copyToClipboard(context),
              onRetake: () => Navigator.of(context).pop(),
            ),
          ],
        ),
      ),
    );
  }

  // ── AppBar ────────────────────────────────────────────────────────────────

  PreferredSizeWidget _buildAppBar(BuildContext context) {
    return AppBar(
      title: const Text('ANALYSIS RESULTS'),
      leading: IconButton(
        icon: const Icon(Icons.arrow_back_ios_new_rounded,
            color: AppColors.neonCyan, size: 20),
        onPressed: () => Navigator.of(context).pop(),
      ),
      actions: [
        Padding(
          padding: const EdgeInsets.only(right: 12),
          child: _StatusPill(status: posture.status),
        ),
      ],
    );
  }

  // ── Copy to clipboard ─────────────────────────────────────────────────────

  void _copyToClipboard(BuildContext context) {
    final buffer = StringBuffer()
      ..writeln('═══ BODY AI — RESULTS ═══')
      ..writeln('Captured: ${_formatDate(capturedAt)}')
      ..writeln('Calibration: ${calibration.summary}')
      ..writeln()
      ..writeln('── MEASUREMENTS ──')
      ..writeln(_measurementText())
      ..writeln()
      ..writeln('── JOINT ANGLES ──')
      ..writeln(_angleText())
      ..writeln()
      ..writeln('── POSTURE ──')
      ..writeln('Status: ${posture.status.label}')
      ..writeln('Shoulder tilt: ${posture.shoulderTiltDeg.toStringAsFixed(1)}°')
      ..writeln('Spine tilt:    ${posture.spineTiltDeg.toStringAsFixed(1)}°')
      ..writeln('Hip tilt:      ${posture.hipTiltDeg.toStringAsFixed(1)}°')
      ..writeln()
      ..writeln('Generated by Body AI');

    Clipboard.setData(ClipboardData(text: buffer.toString()));
    HapticFeedback.lightImpact();
    ScaffoldMessenger.of(context).showSnackBar(
      const SnackBar(
        content: Text('Results copied to clipboard'),
        backgroundColor: AppColors.neonGreen,
        duration: Duration(seconds: 2),
      ),
    );
  }

  String _measurementText() {
    final m = measurement;
    final lines = <String>[];
    void add(String k, double? v) {
      if (v != null) lines.add('$k: ${v.toStringAsFixed(1)} cm');
    }
    add('Height',         m.bodyHeightCm);
    add('Shoulder Width', m.shoulderWidthCm);
    add('Chest Width',    m.chestWidthCm);
    add('Torso Length',   m.torsoLengthCm);
    add('Hip Width',      m.hipWidthCm);
    add('L. Arm Length',  m.leftArmLengthCm);
    add('R. Arm Length',  m.rightArmLengthCm);
    add('L. Forearm',     m.leftForearmCm);
    add('R. Forearm',     m.rightForearmCm);
    add('L. Thigh',       m.leftThighCm);
    add('R. Thigh',       m.rightThighCm);
    add('L. Shin',        m.leftShinCm);
    add('R. Shin',        m.rightShinCm);
    return lines.join('\n');
  }

  String _angleText() {
    final m = measurement;
    final lines = <String>[];
    void add(String k, double? v) {
      if (v != null) lines.add('$k: ${v.toStringAsFixed(0)}°');
    }
    add('L. Elbow',    m.elbowAngleLeft);
    add('R. Elbow',    m.elbowAngleRight);
    add('L. Knee',     m.kneeAngleLeft);
    add('R. Knee',     m.kneeAngleRight);
    add('L. Shoulder', m.shoulderAngleLeft);
    add('R. Shoulder', m.shoulderAngleRight);
    add('L. Hip',      m.hipAngleLeft);
    add('R. Hip',      m.hipAngleRight);
    return lines.join('\n');
  }

  Color _postureColor(PostureStatus s) {
    switch (s) {
      case PostureStatus.stable:           return AppColors.neonGreen;
      case PostureStatus.unstableRotation: return AppColors.neonRed;
      default:                             return AppColors.neonOrange;
    }
  }

  String _formatDate(DateTime dt) =>
      '${dt.year}-${_p(dt.month)}-${_p(dt.day)}  '
      '${_p(dt.hour)}:${_p(dt.minute)}:${_p(dt.second)}';

  String _p(int n) => n.toString().padLeft(2, '0');
}

