class _MeasurementsGrid extends StatelessWidget {
  const _MeasurementsGrid({required this.measurement});
  final MeasurementResult measurement;

  @override
  Widget build(BuildContext context) {
    final m = measurement;

    final rows = <_MeasRow>[
      _MeasRow('Body Height',    m.bodyHeightCm,    isPrimary: true),
      _MeasRow('Shoulder Width', m.shoulderWidthCm, isPrimary: true),
      _MeasRow('Chest Width',    m.chestWidthCm),
      _MeasRow('Torso Length',   m.torsoLengthCm,   isPrimary: true),
      _MeasRow('Hip Width',      m.hipWidthCm,      isPrimary: true),
      _MeasRow('L. Arm Length',  m.leftArmLengthCm),
      _MeasRow('R. Arm Length',  m.rightArmLengthCm),
      _MeasRow('L. Forearm',     m.leftForearmCm),
      _MeasRow('R. Forearm',     m.rightForearmCm),
      _MeasRow('L. Thigh',       m.leftThighCm),
      _MeasRow('R. Thigh',       m.rightThighCm),
      _MeasRow('L. Shin',        m.leftShinCm),
      _MeasRow('R. Shin',        m.rightShinCm),
    ].where((r) => r.value != null).toList();

    return Column(
      children: rows
          .map((r) => _MeasurementRow(row: r))
          .toList(),
    );
  }
}

class _MeasRow {
  const _MeasRow(this.label, this.value, {this.isPrimary = false});
  final String  label;
  final double? value;
  final bool    isPrimary;
}

class _MeasurementRow extends StatelessWidget {
  const _MeasurementRow({required this.row});
  final _MeasRow row;

  @override
  Widget build(BuildContext context) {
    final valueColor = row.isPrimary ? AppColors.neonCyan : AppColors.textPrimary;
    return Padding(
      padding: const EdgeInsets.symmetric(vertical: 5),
      child: Row(
        mainAxisAlignment: MainAxisAlignment.spaceBetween,
        children: [
          Text(
            row.label,
            style: const TextStyle(
              fontFamily: 'Courier',
              fontSize:   12,
              color:      AppColors.textSecondary,
            ),
          ),
          Row(
            children: [
              Text(
                row.value!.toStringAsFixed(1),
                style: TextStyle(
                  fontFamily:  'Courier',
                  fontSize:    row.isPrimary ? 16 : 14,
                  fontWeight:  FontWeight.w700,
                  color:       valueColor,
                ),
              ),
              const SizedBox(width: 4),
              const Text(
                'cm',
                style: TextStyle(
                  fontFamily: 'Courier',
                  fontSize:   10,
                  color:      AppColors.textDisabled,
                ),
              ),
            ],
          ),
        ],
      ),
    );
  }
}

