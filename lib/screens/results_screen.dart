class _StatusPill extends StatelessWidget {
  const _StatusPill({required this.status});
  final PostureStatus status;

  @override
  Widget build(BuildContext context) {
    Color c;
    switch (status) {
      case PostureStatus.stable:           c = AppColors.neonGreen;  break;
      case PostureStatus.unstableRotation: c = AppColors.neonRed;    break;
      default:                             c = AppColors.neonOrange;
    }
    return Container(
      padding: const EdgeInsets.symmetric(horizontal: 8, vertical: 4),
      decoration: BoxDecoration(
        color:        c.withOpacity(0.12),
        borderRadius: BorderRadius.circular(5),
        border: Border.all(color: c.withOpacity(0.5)),
      ),
      child: Text(
        status == PostureStatus.stable ? 'STABLE' : 'ALERT',
        style: TextStyle(
          fontFamily:   'Courier',
          fontSize:     9,
          fontWeight:   FontWeight.w700,
          color:        c,
          letterSpacing: 1.2,
        ),
      ),
    );
  }
}

